let fruit = "Mango";

switch (fruit) {
    case "Apple":
        console.log("Apples are great for making pies.");
    case "Banana":
        console.log("Bananas are perfect for smoothies.");
    case "Mango":
        console.log("Mangoes are delicious in desserts.");
    case "Orange":
        console.log("Oranges are refreshing in juices.");
    default:
        console.log("Unknown fruit");
}