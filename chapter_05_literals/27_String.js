// Single quote
let singleQuoteString = 'Hello, World!';
console.log(singleQuoteString); // Output: Hello, World!

let quote = 'She said, "Hello!"';
// Using single quotes allows us to include double quotes without escaping
console.log(quote); // Output: She said, "Hello!"

// double quote
let doubleQuoteString = "Hello, World!";
console.log(doubleQuoteString); // Output: Hello, World!

// javscript does not have any character concept like other programming languages, 
// it treats characters as strings of length 1
// So everthing is a string in JavaScript, even a single character is a string of length 1
let char = 'A'; // This is a string of length 1, not a character type
let char2 = 'CC';
console.log(char); // Output: A
console.log(char2); // Output: CC
console.log(typeof char); // Output: "string"
console.log(typeof char2); // Output: "string" 

