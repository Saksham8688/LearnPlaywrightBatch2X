let name = "SAKSHAM"; //This is string literal assigned to the variable name
let age = 25; // This is a number literal assigned to the variable age
let isStudent = true; // This is a boolean literal assigned to the variable isStudent
let city = null; // This is a null literal assigned to the variable city
let undefinedValue; // This variable is declared but not assigned, so it has the value undefined
let pi = 3.14; // This is a number literal (floating-point) assigned to the variable pi

// typeof operator can be used to check the type of literals
console.log(typeof name); // Output: "string"
console.log(typeof age); // Output: "number"
console.log(typeof isStudent); // Output: "boolean"
console.log(typeof city); // Output: "object" (this is a known quirk in JavaScript)
console.log(typeof undefinedValue); // Output: "undefined" 
console.log(typeof pi); // Output: "number"  