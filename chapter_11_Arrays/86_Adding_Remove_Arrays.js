let arr = [1, 2, 3];

console.log(arr);

//Add at the end 
arr.push(4);
console.log(arr);

//Remove at the end
arr.pop();
console.log(arr);

//Push multiple elements
arr.push(5, 6);
console.log(arr);

//Add at the beginning
arr.unshift(0);
console.log(arr);

// Remove from the beginning
arr.shift();
console.log(arr);