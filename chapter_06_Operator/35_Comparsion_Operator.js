// Comparsion Operators

// > , < , >= , <= , == , === , != , !==

// = -> Assignment Operator
// == -> Loose Comparsion
// === -> Strict Comparsion

console.log(5 > 3); // Output: true
console.log(5 < 3); // Output: false
console.log(5 >= 5); // Output: true  5 > 5 or 5 == 5
console.log(5 <= 4); // Output: false 5 < 4 or 5 == 4